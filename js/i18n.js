const root = document.documentElement;
const EN = { ...EN_EXTRA };

// Remember the English that's in the HTML so we can switch back without reloading.
document.querySelectorAll("[data-i18n]").forEach((el) => (EN[el.dataset.i18n] = el.textContent));
document.querySelectorAll("[data-i18n-alt]").forEach((el) => (EN[el.dataset.i18nAlt] = el.alt));
document.querySelectorAll("[data-i18n-content]").forEach((el) => (EN[el.dataset.i18nContent] = el.content));

function t(key) {
  const dict = root.lang === "fr" ? FR : EN;
  return dict[key] ?? EN[key] ?? key;
}

function apply(lang) {
  root.lang = lang;
  root.setAttribute("data-lang", lang);
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => (el.alt = t(el.dataset.i18nAlt)));
  document.querySelectorAll("[data-i18n-content]").forEach((el) => (el.content = t(el.dataset.i18nContent)));

  // The switch shows the *other* language.
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.textContent = lang === "fr" ? "EN" : "FR";
    btn.setAttribute("aria-label", lang === "fr" ? "Switch to English" : "Passer en français");
  });
  root.classList.add("i18n-ready");
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
}

function setLang(lang) {
  try { localStorage.setItem("lang", lang); } catch (e) {}
  // Keep the URL shareable: /?lang=fr opens in French.
  try {
    const url = new URL(location.href);
    url.searchParams.set("lang", lang);
    history.replaceState(null, "", url);
  } catch (e) {}
  apply(lang);
}

document.querySelectorAll("[data-lang-toggle]").forEach((btn) =>
  btn.addEventListener("click", () => setLang(root.lang === "fr" ? "en" : "fr"))
);

window.i18n = { t, setLang };
apply(root.lang === "fr" ? "fr" : "en");
